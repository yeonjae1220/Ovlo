-- 기존 승인/문의는 보존한다. 출처 검토와 과거 인용 버전을 소급해서 만들어 내지 않는다.
ALTER TABLE office_notice ADD COLUMN row_version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE office_notice ADD COLUMN source_metadata TEXT;
ALTER TABLE office_notice ADD COLUMN review_metadata TEXT;
ALTER TABLE office_notice ADD COLUMN next_review_on DATE;
CREATE INDEX idx_notice_review_due ON office_notice (status, next_review_on);
CREATE TABLE office_source_scope (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 office_id BIGINT NOT NULL REFERENCES office(id), department VARCHAR(200) NOT NULL,
 url VARCHAR(1000) NOT NULL, enabled BOOLEAN NOT NULL, revision BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_source_scope_office ON office_source_scope(office_id);
CREATE TABLE office_notice_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 office_id BIGINT NOT NULL REFERENCES office(id), notice_id BIGINT NOT NULL REFERENCES office_notice(id),
 source_version INTEGER NOT NULL, actor_id BIGINT NOT NULL, action VARCHAR(50) NOT NULL,
 evidence TEXT, snapshot TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_notice_audit_history ON office_notice_audit(office_id,notice_id,id);
CREATE TABLE office_inquiry_evidence (
 id BIGINT PRIMARY KEY REFERENCES office_inquiry(id), payload TEXT NOT NULL
);
CREATE TABLE office_notice_reminder (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 notice_id BIGINT NOT NULL REFERENCES office_notice(id), due_on DATE NOT NULL, overdue BOOLEAN NOT NULL,
 UNIQUE(notice_id,due_on,overdue)
);
